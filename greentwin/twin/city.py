"""Demo city: many homes' digital twins computed once in batch, with the business insights the Lloyds dashboard reads.

Homes: a synthetic city over real Manchester postcode districts (``city_assumptions.json``), generated by a documented,
seeded rule. Loft insulation and low-energy lighting follow p3's EPC-fitted priors (``greentwin/score/priors.json``).
Small areas are synthetic ids like ``M14-03`` (never real LSOA codes). Swap ``synthetic_homes`` for an EPC extract
mapper when real records are available; everything downstream stays the same.

Per home: twin parameters + provenance (``build_physics_inputs``), prior samples, baseline and standard packages
re-simulated as a whole (batched: one vmapped physics call per fuel group per package), then the insights of
``docs/business_insight.md`` step 1: self-funding loans (2.3), price stress test (2.4), carbon per £ (2.5),
confidence-tiered offers (2.6) and street deals (2.10).
"""

