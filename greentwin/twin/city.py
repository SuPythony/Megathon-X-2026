# --------------------------------------------------------------------------- models
class SyntheticHome(BaseModel):
    prop: Property
    archetype_id: str
    small_area: str
    is_customer: bool
    has_12_months_bills: bool
    geometry_confirmed: bool


class CityPackage(BaseModel):
    retrofit_ids: list[str]
    cost_gbp: Optional[float] = Field(None, description="Catalogue central cost; None if any item is unsourced")
    cost_note: str
    monthly_repayment_gbp: Optional[float] = None
    bill_saving_gbp: Range
    gas_saving_kwh: Range
    electricity_saving_kwh: Range
    carbon_saving_kg: Range
    p_self_funding: Optional[float] = Field(None, description="P(monthly bill saving >= loan repayment)")
    p_bill_falls: float = Field(description="P(bill saving > 0)")
    carbon_per_1k_lent_kg: Optional[float] = None


class StressResult(BaseModel):
    bill_before_gbp: Range
    p_over_before: float
    bill_after_gbp: Optional[Range] = None
    p_over_after: Optional[float] = None


class CityHome(BaseModel):
    property_id: str
    district: str
    small_area: str
    archetype_id: str
    property_type: str
    built_form: str
    age_band: str
    tenure: str
    heating_fuel: str
    floor_area_m2: float
    is_customer: bool
    has_12_months_bills: bool
    geometry_confirmed: bool
    confidence_tier: Optional[str] = Field(None, description="A instant / B desk check / C survey first (customers)")
    confirmed_or_recorded_heat_loss_pct: float
    baseline_bill_gbp: Range
    baseline_carbon_kg: Range
    packages: dict[str, Optional[CityPackage]]
    best_package: Optional[str] = None
    stress: dict[str, StressResult]
    street_deal: Optional[str] = None
    engine: str


class CityArea(DashboardArea):
    """DashboardArea plus the step-1 insight layers (proposed contract extension, docs/business_insight.md §5)."""

