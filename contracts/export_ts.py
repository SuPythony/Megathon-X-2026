"""Generate contracts/types.ts from contracts/models.py (the TS mirror is never hand-edited).

Run:  python -m contracts.export_ts
"""

from __future__ import annotations

import enum
import json
from pathlib import Path

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from . import models

OUT = Path(__file__).parent / "types.ts"


def _all_models() -> list[type[BaseModel]]:
    return [v for v in vars(models).values()
            if isinstance(v, type) and issubclass(v, BaseModel) and v is not BaseModel and v.__module__ == models.__name__]


def _ts(schema: dict) -> str:
    """JSON Schema fragment -> TypeScript type expression."""
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = []
            for s in schema[key]:
                t = _ts(s)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts(s) for s in schema["prefixItems"]) + "]"
        inner = _ts(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {_ts(ap)}>"
        return "Record<string, unknown>"
    return "unknown"


def _doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    text = " ".join(text.split())
    return f"{indent}/** {text} */\n"


def render() -> str:
    _, top = models_json_schema([(m, "validation") for m in _all_models()], ref_template="#/$defs/{model}")
    defs = top["$defs"]
    lines = [
        "// GENERATED by `python -m contracts.export_ts` from contracts/models.py. DO NOT EDIT BY HAND.",
        "// Units: kWh/yr, GBP, kgCO2e, m2, W/m2K, W/K. Savings = baseline - after (negative = increase).",
        "// Every uncertain number is a Distribution (mean, median, mode, std, percentiles, intervals, tails).",
        "",
        f'export const SCHEMA_VERSION = "{models.SCHEMA_VERSION}";',
        "",
    ]
    order = [m.__name__ for m in _all_models()] + [k for k in defs if k not in {m.__name__ for m in _all_models()}]
    seen = set()
    for name in order:
        if name not in defs or name in seen:
            continue
        seen.add(name)
        d = defs[name]
        cls = getattr(models, name, None)
        if "enum" in d:  # str Enum
            lines.append(_doc(d.get("description")) + f"export type {name} = {_ts(d)};")
            lines.append("")
            continue
        doc = (cls.__doc__ if cls is not None and isinstance(cls, type) and issubclass(cls, BaseModel)
               and cls.__doc__ and not cls.__doc__.startswith("!!!") else d.get("description"))
        if cls is not None and isinstance(cls, type) and issubclass(cls, enum.Enum):
            doc = None
        lines.append(_doc(doc) + f"export interface {name} {{")
        req = set(d.get("required", []))
        for prop, ps in d.get("properties", {}).items():
            t = _ts(ps)
            opt = "" if prop in req else "?"
            lines.append(_doc(ps.get("description"), "  ") + f"  {prop}{opt}: {t};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).replace("\n\n\n", "\n\n")


def main() -> None:
    OUT.write_text(render(), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
