"""Write docs/M04_ENERGY_PRIOR.md (model card) from the run's results, so every number is copied by code.

    uv run python scripts/model_card_energy_prior.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "artifacts/m04_energy_prior/v2"
ORDER = ["global_mean", "need_median", "ols_linear", "ols_onehot", "ols_log", "ridge", "lasso", "poly2_ridge",
         "xgboost", "lightgbm", "ebm"]


def f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default=str(RUN))
    ap.add_argument("--out", default=str(ROOT / "docs/M04_ENERGY_PRIOR.md"))
    args = ap.parse_args()
    run = Path(args.run)
    res = json.loads((run / "results.json").read_text())
    cfg = json.loads((run / "config.json").read_text())
    bayes = json.loads((run / "bayes.json").read_text()) if (run / "bayes.json").exists() else None
    sb = json.loads((run / "showcase_bayes.json").read_text()) if (run / "showcase_bayes.json").exists() else None
    names = res["model_names"]
    L = []
    w = L.append
    w("# M04 energy-intensity prior — model card\n")
    w("Generated by `scripts/model_card_energy_prior.py` from `artifacts/m04_energy_prior/v2/`. "
      "Interactive report: `eval/reports/m04/report.html`. Plan: `docs/M04_PLAN.md`.\n")
    w("## What it is\n")
    w("Predicts a home's annual **electricity** and **gas** intensity (kWh/m²/yr) from the fields a GreenTwin "
      "`Property` carries, as a full predictive `Distribution` plus additive EBM contributions (`EnergyPrior` "
      "contract). It is the prior for homes without meters and the centre of the Bayesian calibration (M09). "
      "It never produces customer savings; the physics twin does.\n")
    w("## Data\n")
    w(f"- **Source:** {cfg['source']}.")
    w(f"- **Target:** mean of valid (flag `V`) readings {cfg['target_years'][0]}–{cfg['target_years'][-1]} ÷ "
      f"representative floor area of the NEED band {cfg['floor_band_area_m2']} m² (bands only in NEED).")
    w("- Gas: gas-heated homes only, weather-corrected by DESNZ. Electricity: all homes, not weather-corrected.")
    w(f"- **Split:** by property, stratified on {' × '.join(cfg['split']['strata'])}; "
      "60% train / 10% tune / 10% calibration / 20% test, seed 42.")
    w("- **Excluded:** " + "; ".join(f"`{k}` ({v})" for k, v in cfg["excluded_features"].items()) + ".")
    w(f"- 20% of training homes have IMD masked (`imd_mask_frac={cfg['imd_mask_frac']}`) so 'unknown' is learnt.\n")

    for fuel in ("electricity", "gas"):
        r = res[fuel]
        t, iv, bs = r["test"], r["intervals"], r["bootstrap"]
        w(f"## Results — {fuel}\n")
        w(f"Test homes: {r['n']['test']:,} · train {r['n']['train']:,} ({r['n']['train_cells']:,} unique feature cells) "
          f"· tune {r['n']['tune']:,} · calibration {r['n']['cal']:,}.\n")
        w("| Model | R² (95% CI) | MAE | RMSE | MAPE | MdAPE | Bias | 90% cover | 90% width |")
        w("|---|---|---|---|---|---|---|---|---|")
        for k in ORDER:
            if k not in t:
                continue
            ci = bs["models"][k]["r2_ci95"]
            b = "**" if k == "ebm" else ""
            w(f"| {b}{names[k]}{b} | {f(t[k]['r2'])} ({f(ci[0])}–{f(ci[1])}) | {f(t[k]['mae'], 2)} | "
              f"{f(t[k]['rmse'], 2)} | {f(t[k]['mape_pct'], 1)}% | {f(t[k]['mdape_pct'], 1)}% | {f(t[k]['bias'], 2)} | "
              f"{100 * iv[k]['coverage']:.1f}% | {f(iv[k]['mean_width'], 1)} |")
        w(f"\n**EBM vs each model (paired bootstrap, {bs['n_boot']:,} resamples of test homes).** "
          "Gain = MAE(model) − MAE(EBM); positive means EBM is better.\n")
        w("| vs | MAE gain (kWh/m²/yr) | 95% CI | % | R² gain | 95% CI |")
        w("|---|---|---|---|---|---|")
        for k, d in bs["delta_vs_reference"].items():
            w(f"| {names[k]} | {f(d['mae_gain'], 3)} | {f(d['mae_gain_ci95'][0], 3)} to {f(d['mae_gain_ci95'][1], 3)} | "
              f"{f(d['mae_gain_pct'], 1)}% | {f(d['r2_gain'], 4)} | {f(d['r2_gain_ci95'][0], 4)} to {f(d['r2_gain_ci95'][1], 4)} |")
        c = r["ceiling"]["all_features"]
        a = r["archetype"]
        w(f"\n- **Explainable-variance ceiling** (ω², bias-corrected between-cell share over {c['cells']:,} cells): "
          f"{f(c['omega2_unbiased'])} (in-sample η² {f(c['eta2_in_sample'])}). EBM reaches "
          f"**{100 * t['ebm']['r2'] / c['omega2_unbiased']:.1f}%** of it.")
        w(f"- **Archetype level** (type × age × floor band × region, ≥ 50 test homes, {a['ebm']['cells']} cells): "
          f"R² EBM {f(a['ebm']['r2'])}, poly-2 ridge {f(a['poly2_ridge']['r2'])}, OLS {f(a['ols_onehot']['r2'])}, "
          f"NEED median {f(a['need_median']['r2'])}.")
        w(f"- **IMD unknown** (as for most Property records): EBM R² {f(r['ebm_imd_unknown']['r2'])}, "
          f"MAE {f(r['ebm_imd_unknown']['mae'], 2)}.")
        mono = r["monotonicity"]
        mp = r.get("monotonicity_poly2_ridge", {})
        w("- **Physics monotonicity** (each constrained feature swept on test homes): EBM "
          + ", ".join(f"`{k}` {v['violations']} of {v['checked']:,}" for k, v in mono.items())
          + "; poly-2 ridge " + ", ".join(f"`{k}` {v['violations']:,} of {v['checked']:,}" for k, v in mp.items()) + ".")
        w(f"- **Additivity:** max |Σ contributions − prediction| over all test homes = {r['local_additivity_max_abs_err']:.1e}.")
        top = list(r["ebm_global"]["terms"])[:6]
        w("- **Top EBM terms:** " + ", ".join(f"{x['label']} ({x['importance']:.2f})" for x in top) + ".")
        w("- **Chosen hyperparameters:** " + "; ".join(f"{names[m]}: " + ", ".join(f"{k}={v}" for k, v in p.items())
                                                      for m, p in r["best_params"].items()) + ".")
        ls = r.get("linear_search", {})
        if ls:
            w("- **Penalty search (tune split):** " + "; ".join(f"{names[k]} α={v['chosen_alpha']}" for k, v in ls.items()) + ".")
        w("")

    hyb = json.loads((run / "hybrid.json").read_text()) if (run / "hybrid.json").exists() else None
    if hyb:
        w("## Served model: EBM + monotone LightGBM correction\n")
        w("Prediction = every EBM term + one 'higher-order interactions (tree correction)' term from a LightGBM fitted "
          "to the EBM's residuals under the same monotone constraints, replaced by its monotone envelope so the "
          "constraint holds exactly. Gates (all must pass to serve): " + ("**passed**" if hyb["passed"] else "**not passed**") + ".\n")
        w("| Fuel | EBM R² / MAE | Hybrid R² / MAE | LightGBM R² / MAE | Coverage | PIT KS | Violations | Mean |correction| |")
        w("|---|---|---|---|---|---|---|---|")
        for fuel in ("electricity", "gas"):
            h, t = hyb[fuel], hyb[fuel]["test"]
            w(f"| {fuel} | {f(t['ebm']['r2'])} / {f(t['ebm']['mae'], 2)} | **{f(t['hybrid']['r2'])} / {f(t['hybrid']['mae'], 2)}** | "
              f"{f(t['lightgbm']['r2'])} / {f(t['lightgbm']['mae'], 2)} | {100 * h['interval_90']['coverage']:.1f}% | "
              f"{f(h['pit_ks'], 4)} | {sum(v['violations'] for v in h['monotonicity'].values())} | {f(h['correction']['mean_abs'], 2)} |")
        w("\nThe EBM-only model is kept as `artifacts/m04_energy_prior/v2/model_ebm_only.pkl`. The 11-model ladder "
          "below reports the EBM component.\n")
    diag = json.loads((run / "diagnostics.json").read_text()) if (run / "diagnostics.json").exists() else None
    if diag:
        w("## Training diagnostics\n")
        for fuel in ("electricity", "gas"):
            g = diag[fuel]
            w(f"**{fuel}** — served EBM on each split: " + ", ".join(
                f"{k} R² {f(v['r2'])} / MAE {f(v['mae'], 2)} (n={v['n']:,})" for k, v in g["by_split"].items()) + ".")
            w("Learning curve (test R²): " + ", ".join(f"{r['homes']:,} homes → {f(r['test_r2'], 4)}"
                                                        for r in g["learning_curve"]) + ".")
            w(f"PIT max deviation from uniform {f(g['pit']['ks_distance_from_uniform'], 4)}; reliability: " + ", ".join(
                f"{100 * r['nominal']:.0f}% → {100 * r['empirical']:.1f}%" for r in g["pit"]["reliability"]) + ".\n")
    if bayes:
        w("## Bayesian update with a home's own meters\n")
        w("Posterior ∝ prior (M04 predictive) × likelihood of annual readings. Likelihood: "
          "log(reading) = log(θ) + ε, ε ~ Student-t, fitted on NEED homes with valid 2022 and 2023 readings. "
          "Importance sampling over 4,000 prior draws; held-out test predicts each home's unseen 2023 reading.\n")
        w("| Fuel | ν | scale | pairs | area elasticity β (95% CI) |")
        w("|---|---|---|---|---|")
        for fuel in ("electricity", "gas"):
            n, ae = bayes[fuel]["noise"], bayes[fuel]["area_elasticity"]
            w(f"| {fuel} | {f(n['nu'], 2)} | {f(n['scale'])} | {n['n_pairs']:,} | {f(ae['beta'])} "
              f"({f(ae['ci95'][0])}–{f(ae['ci95'][1])}) |")
        for fuel in ("electricity", "gas"):
            u = bayes[fuel]["update_test"]
            w(f"\n**{fuel}** — {u['n_homes']:,} held-out homes; median ESS {u['median_ess_1yr']:.0f}/4,000 (1 yr).\n")
            w("| Method | MAE | Median AE | 90% coverage | 90% width | CRPS |")
            w("|---|---|---|---|---|---|")
            for k, lab in (("prior_only", "Prior only"), ("posterior_1yr", "Posterior, 1 yr"),
                           ("posterior_2yr", "Posterior, 2 yrs"), ("persistence", "Persistence (2023 = 2022)")):
                x = u["results"][k]
                w(f"| {lab} | {f(x['mae'], 2)} | {f(x['mdae'], 2)} | {100 * x['coverage_90']:.1f}% | "
                  f"{f(x['mean_width_90'], 1)} | {f(x['crps'], 2)} |")
        w("\nAssumptions (labelled): " + "; ".join(f"{k} = {v['value']} ({v['status']})" for k, v in bayes["assumptions"].items()) + ".\n")
    if sb:
        w("## Showcase homes (full distributions, kWh/m²/yr)\n")
        w("| Home | Fuel | Metered | Prior mean / median / SD | Posterior mean / median / mode / SD | Posterior 90% CI | P(above peers) | SD ↓ |")
        w("|---|---|---|---|---|---|---|---|")
        for sh, r in sb.items():
            for fuel, v in r["fuels"].items():
                if "prior" not in v:
                    w(f"| {sh} | {fuel} | – | {v['note']} | | | | |")
                    continue
                p, q = v["prior"], v["posterior"]
                ci = next(c for c in q["credible_intervals"] if c["level"] == 0.9)
                tail = f"{100 * q['tail_probabilities'][0]['probability']:.0f}%" if q["tail_probabilities"] else "–"
                w(f"| {sh} | {fuel} | {v['observed']['intensity_kwh_m2']:.1f} | {p['mean']:.1f} / {p['median']:.1f} / {p['std']:.1f} | "
                  f"{q['mean']:.1f} / {q['median']:.1f} / {q['mode']:.1f} / {q['std']:.1f} | {ci['lo']:.1f}–{ci['hi']:.1f} | {tail} | "
                  f"{v['sd_reduction_pct']:.0f}% |")
        w("")
    w("## Using it\n")
    w("- Python: `from greentwin.models.energy_prior import energy_prior` → `EnergyPrior`; "
      "`greentwin.models.prior_update.update_with_meters(load_default(), prop, usage)` → prior/posterior per fuel.")
    w("- CLI: `uv run python -m greentwin.models.energy_prior contracts/examples/SH2_property.json "
      "--usage contracts/examples/SH2_usage_2025.json`.")
    w("- HTTP: `greentwin.api.energy_prior.router` (mount with `app.include_router(router)`): "
      "`POST /m04/energy-prior`, `POST /m04/energy-prior/update`, `GET /m04/health`. "
      "Standalone: `uv run uvicorn greentwin.api.energy_prior:app --port 8040`.")
    w("- Monitoring: `uv run python scripts/check_energy_prior.py` (10 checks: artefacts, contract, additivity, "
      "monotonicity, Bayesian update, quality thresholds, staleness, HTTP round-trip, fresh re-score of held-out "
      "homes); each pass is appended to `artifacts/m04_energy_prior/v2/monitor.log`.")
    w("- Repo notes: the trained `model.pkl` (≈250 KB) is committed despite the `*.pkl` ignore rule so the API and "
      "demo work without a 1 GB download and retraining; `uv.lock` is not committed (the repo does not track one).\n")
    w("## Limits\n")
    w("- Per-home R² is bounded by behaviour that no NEED field records; the ceiling quantifies this.")
    w("- NEED floor area is banded; intensity uses band midpoints, with a fitted within-band area elasticity.")
    w("- `MAIN_HEAT_FUEL` is gas vs not-gas only: electric-, oil- and LPG-heated homes share one group.")
    w("- LI/CWI flags mean 'installed under a government scheme since 2000'; mapped from Property fabric as a proxy.")
    w("- Year-to-year noise is fitted on weather-corrected gas; raw meter gas gets an extra labelled weather term.")
    Path(args.out).write_text("\n".join(L) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
