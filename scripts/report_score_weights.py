"""Render artifacts/score_weights/<version>/metrics.json as Markdown (pasted into docs/score/LEARNED_WEIGHTS.md).

    uv run python scripts/report_score_weights.py v1 [out.md]   # default docs/score/LEARNED_WEIGHTS.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMP = ["energy_efficiency", "energy_intensity", "insulation", "heating_system", "windows_glazing",
        "renewable_energy", "smart_energy_management"]
ATTR = ["s_insulation", "s_heating_system", "s_windows_glazing", "s_renewable_energy", "s_smart_energy_management"]
NAME = {"s_insulation": "insulation", "s_heating_system": "heating", "s_windows_glazing": "glazing",
        "s_renewable_energy": "renewables", "s_smart_energy_management": "smart", "s_energy_efficiency": "energy eff.",
        "s_energy_intensity": "intensity"}
TNAME = {"sap": "SAP rating (cost)", "eir": "EIR (carbon rating)", "co2_m2": "−CO₂ per m²", "pe_m2": "−primary energy per m²"}


def main() -> None:
    v = sys.argv[1] if len(sys.argv) > 1 else "v1"
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "docs" / "score" / "LEARNED_WEIGHTS.md"
    mt = json.loads((ROOT / "artifacts" / "score_weights" / v / "metrics.json").read_text())
    e, c, fw, bw = mt["epc"], mt["cells"], mt["final_weights"], mt["brief_weights"]
    lines: list[str] = []

    def p(s: str = "") -> None:
        lines.append(s)
    p(f"# Learned Green Home Score weights ({v})\n")
    p("Generated by `scripts/report_score_weights.py` from `artifacts/score_weights/" + v + "/metrics.json` "
      f"(seed {mt['seed']}). Method: `docs/score/DECISIONS.md` D-06 and D-18. The headline score keeps the brief's "
      "fixed weights; these weights power the companion score `ScoreResult.alternatives` (D-05, D-19).\n")

    p("## Final weights\n")
    ci = mt.get("final_weights_boot_p5_p95", {})
    p("| Component | Brief | Learned | Change | 90% bootstrap |\n| --- | --- | --- | --- | --- |")
    for k in COMP:
        band = ci.get(k)
        p(f"| {k} | {bw[k]:.2f} | **{fw[k]:.3f}** | {fw[k] - bw[k]:+.3f} | "
          f"{f'{band[0]:.3f}–{band[1]:.3f}' if band else '—'} |")
    if "attribute_block" in ci:
        p(f"\nThe five attribute components together: 90% bootstrap {ci['attribute_block'][0]:.3f}–"
          f"{ci['attribute_block'][1]:.3f}.\n")

    p(f"## Stage 1: attribute weights from the EPC register\n\n{e['n']:,} properties (latest certificate per "
      f"property; train {e['n_train']:,} / val {e['n_val']:,} / test {e['n_test']:,}, split by property hash).\n")
    p("| Target (higher = greener) | " + " | ".join(NAME[a] for a in ATTR) + " | Test R² learned | brief | equal | LightGBM ceiling |")
    p("| --- " * (len(ATTR) + 5) + "|")
    for t, r in e["targets"].items():
        w = r["nnls_weights"]
        p(f"| {TNAME[t]} | " + " | ".join(f"{w[a]:.3f}" for a in ATTR) +
          f" | **{r['r2_test_learned']:.3f}** | {r['r2_test_brief_weights']:.3f} | {r['r2_test_equal_weights']:.3f} | "
          f"{r['r2_test_lgbm_with_extras']:.3f} |")
    p("\n90% bootstrap ranges of the NNLS weights (SAP target): " + ", ".join(
        f"{NAME[a]} {e['targets']['sap']['nnls_weights_boot_p5'][a]:.3f}–{e['targets']['sap']['nnls_weights_boot_p95'][a]:.3f}"
        for a in ATTR) + ".\n")
    p("Shapley (LMG) R² shares, SAP target: " + ", ".join(
        f"{NAME[a]} {e['targets']['sap']['shapley_r2'][a]:.3f}" for a in ATTR) +
      f" (total R² {e['targets']['sap']['shapley_r2_total']:.3f}).\n")
    p("Grouped monotone-LightGBM |SHAP| shares, SAP target (incl. candidate extras): " + ", ".join(
        f"{k.replace('s_', '')} {v:.3f}" for k, v in e["targets"]["sap"]["lgbm_shap_share"].items()) + ".\n")
    b = e["bayes_sap"]
    p(f"Bayesian check ({b['prior']}), posterior mean [90% CrI]: " + ", ".join(
        f"{NAME[a]} {b['mean'][a]:.3f} [{b['p5'][a]:.3f}, {b['p95'][a]:.3f}]" for a in ATTR) + ".\n")

    es = mt.get("era_stability", {})
    eras = [k for k in es if k not in ("boundaries", "note")]
    if eras:
        p(f"### Stability across EPC methodology eras (D-20)\n\nFinal weights use the **{mt.get('era', 'all')}** era "
          "only. Same stage-1 fit on the older eras (each with its own fuel prices and carbon factors), SAP target:\n")
        p("| Era | n | " + " | ".join(NAME[a] for a in ATTR) + " |\n| --- " * 1 + "| --- " * (len(ATTR) + 1) + "|")
        for k in eras:
            w = es[k]["sap"]
            p(f"| {k} | {es[k]['n']:,} | " + " | ".join(f"{w[a]:.3f}" for a in ATTR) + " |")
        w = e["targets"]["sap"]["nnls_weights"]
        p(f"| **{mt.get('era')}** (used) | {e['n']:,} | " + " | ".join(f"{w[a]:.3f}" for a in ATTR) + " |\n")

    d = mt["need_per_home_diagnostic"]
    p(f"## Stage 2: energy efficiency and intensity, from real meters\n\n**Per home (rejected):** NEED "
      f"{d['n']:,} homes; held-out R² {d['ee_on_metered']['r2_test']:.3f} (EPC band + proxies → metered kWh/m²) and "
      f"{d['int_on_sap']['r2_test']:.3f} (metered intensity + proxies → EPC band). Behaviour dominates single-home "
      "readings and NEED's attributes are coarse flags.\n")
    p(f"**Archetype cells (used):** {c['n_cells']} cells (type × age × floor-area band) with ≥ 30 homes in both "
      f"sources, {c['homes_epc']:,} EPC and {c['homes_need']:,} NEED homes; fitted within floor-area bands.\n")
    for key, label in (("fit_ee_on_metered", "−metered kWh/m² (NEED)"), ("fit_int_on_sap", "SAP rating (EPC)")):
        f = c[key]
        p(f"- Target {label}: within-band R² {f['r2_within_area_band']:.3f}; LMG R² " + ", ".join(
            f"{NAME[k]} {v:.3f}" for k, v in f["lmg_r2"].items()) + ".")
    p(f"\nRatios (outcome component ÷ attribute block, LMG): EE {c['ratio_ee_to_attributes']:.3f} "
      f"(90% {c['ratio_ee_boot_p5_p95'][0]:.3f}–{c['ratio_ee_boot_p5_p95'][1]:.3f}); intensity "
      f"{c['ratio_int_to_attributes']:.3f} (90% {c['ratio_int_boot_p5_p95'][0]:.3f}–{c['ratio_int_boot_p5_p95'][1]:.3f}).\n")

    a = mt["brief_vs_learned_on_epc_test"]
    p(f"## How different are the two scores?\n\nEPC test homes (n = {a['n']:,}; intensity imputed from the archetype "
      f"cell's median metered value): Spearman {a['spearman']:.3f}, same band for {a['band_agreement']:.1%}, mean "
      f"|difference| {a['mean_abs_diff_points']:.2f} points; mean score {a['mean_brief']:.1f} (brief) vs "
      f"{a['mean_learned']:.1f} (learned); share Poor or Very poor {a['share_poor_or_very_poor_brief']:.1%} vs "
      f"{a['share_poor_or_very_poor_learned']:.1%}.\n")

    p("## Limitations\n")
    p("- Stage 1 targets are **modelled** (SAP/RdSAP), not measured; the weights say which levers drive the official "
      "modelled ratings.\n- Stage 2 is ecological (cell averages); it does not prove the same relation inside a single "
      "home.\n- Condensing vs non-condensing gas boilers cannot be told apart in recent EPC text (D-16), so heating "
      "variation within gas homes is understated.\n- Renewables: few homes have PV, so its weight is the least stable "
      "(see the bootstrap range).\n- Agreement with these targets is not proof of real-world savings; the physics twin "
      "remains the only source of energy and savings numbers.")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
