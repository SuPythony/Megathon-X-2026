"""Generate docs/SCORE.md (submission item D) from contracts/score_mapping.json, so the doc can't drift from the code.

    uv run python scripts/build_score_doc.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from greentwin.score import mapping as m  # noqa: E402
from greentwin.score.score import PV_SELF_CONSUMPTION_DEFAULT  # noqa: E402

NAMES = {"energy_efficiency": "Energy efficiency", "energy_intensity": "Energy intensity", "insulation": "Insulation",
         "heating_system": "Heating system", "windows_glazing": "Windows & glazing",
         "renewable_energy": "Renewable energy", "smart_energy_management": "Smart energy management"}


def table(head: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"] + \
        ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def pts(points, x_unit: str) -> list[str]:
    return table([f"Input ({x_unit})", "Sub-score"], [[x, y] for x, y in points])


def pv_example(kwp: float = 4.0, yield_kwh_per_kwp: float = 850.0, area: float = 95.0, intensity: float = 170.0):
    gen = kwp * yield_kwh_per_kwp
    self_m2 = gen * PV_SELF_CONSUMPTION_DEFAULT / area
    d = float(m.intensity_sub(intensity) - m.intensity_sub(intensity + self_m2))
    return gen, self_m2, d, m.weights()["energy_intensity"] * d, m.weights()["renewable_energy"] * m.renewables_sub(kwp)


def main() -> None:
    cfg = m.mapping()
    c = cfg["components"]
    w = cfg["weights"]
    out = ["# Green Home Score: method, mapping tables and overlap justification",
           "",
           f"_Generated by `scripts/build_score_doc.py` from `contracts/score_mapping.json` v{cfg['version']}. "
           "Do not edit by hand. Decisions, proofs and worked examples: `docs/score/DECISIONS.md`; standards research: "
           "`docs/score/GREEN_SCORE_STANDARDS.md`; learned-weight companion: `docs/score/LEARNED_WEIGHTS.md`._",
           "",
           "## 1. Formula",
           "",
           "S = Σ_k w_k · s_k, with the problem statement's fixed weights w_k and sub-scores s_k in [0, 100]. "
           f"{cfg['rounding']} Every sub-score is monotonic: a better state never gets a lower sub-score "
           "(enforced by sweeps in `tests/test_score.py`).",
           "",
           "Uncertain inputs (metered intensity from the calibrated twin, missing loft depth or lighting share, a missing "
           "rating) are sampled, so the score is reported as a `Distribution` with band probabilities, e.g. "
           "\"38 (90% CI 33–44), P(Poor) = 0.81\". Missing data is sampled from documented priors, never set to 0.",
           "",
           "### Weights",
           ""]
    out += table(["Component", "Weight"], [[NAMES[k], f"{v:.2f}"] for k, v in w.items()] + [["**Total**", f"{sum(w.values()):.2f}"]])
    out += ["", "### Classification (of the rounded score)", ""]
    out += table(["Score", "Band"], [[f"{b['min']}–{b['max']}", b["band"]] for b in cfg["classification"]])

    out += ["", "## 2. Sub-score mappings", ""]
    ee = c["energy_efficiency"]
    out += ["### 2.1 Energy efficiency (0.25)", "", f"- Input: {ee['input']}.", f"- Rule: {ee['rule']}.",
            f"- After a retrofit: {ee['post_retrofit']}", f"- Why: {ee['justification']}", ""]
    out += table(["EPC band (no SAP)", "Midpoint used"], [[b, v] for b, v in ee["band_midpoints"].items()])

    ei = c["energy_intensity"]
    out += ["", "### 2.2 Energy intensity (0.20)", "", f"- Input: {ei['input']}", f"- Annualisation: {ei['annualisation']}",
            f"- Sensitivity: {ei['sensitivity']}", f"- Direction: {ei['direction']}. Why: {ei['justification']}", ""]
    out += pts(ei["points"], "kWh/m²/yr")

    ins = c["insulation"]
    out += ["", "### 2.3 Insulation (0.15)", "",
            "Element weights: " + ", ".join(f"{k} {v:.2f}" for k, v in ins["element_weights"].items()) + ". "
            + ins["renormalise_when_absent"], "", f"Loft (pitched roof): {ins['roof_loft_rule']}.", ""]
    out += pts(ins["roof_loft_mm_points"], "loft mm")
    out += ["", "Other roofs:", ""] + table(["Roof", "Sub-score"], [[k.replace("_", " "), v] for k, v in ins["roof_other"].items()])
    out += ["", "Walls (by category):", ""] + table(["Wall state", "Sub-score"], [[k.replace("_", " "), v] for k, v in ins["walls"].items()])
    out += ["", "Floor (by category):", ""] + table(["Floor", "Sub-score"], [[k, v] for k, v in ins["floor"].items()])
    out += ["", f"U-values: {ins['u_value_rule']}", "", "Wall U-value curve:", ""] + pts(ins["wall_u_points"], "W/m²K")
    out += ["", "Floor U-value curve:", ""] + pts(ins["floor_u_points"], "W/m²K")
    out += ["", f"Roof U-value → equivalent loft depth ({ins['roof_u_to_loft_mm']['source']}):", ""]
    out += table(["Roof U (W/m²K)", "Equivalent loft mm"], ins["roof_u_to_loft_mm"]["points"])
    out += ["", f"Why: {ins['justification']}"]

    hs = c["heating_system"]
    out += ["", "### 2.4 Heating system (0.15)", "", f"- Input: {hs['input']}. {hs['age_adjustment']}",
            f"- Why: {hs['justification']} Every `HeatingSystem` value is mapped (test-enforced).", ""]
    out += table(["System", "Sub-score"], [[k.replace("_", " "), v] for k, v in sorted(hs["map"].items(), key=lambda x: -x[1])])

    g = c["windows_glazing"]
    out += ["", "### 2.5 Windows & glazing (0.10)", "", f"- Input: {g['input']} (area-share weighted mean).", ""]
    out += table(["Glazing", "Sub-score"], [[k.replace("_", " "), v] for k, v in g["map"].items()])

    r = c["renewable_energy"]
    out += ["", "### 2.6 Renewable energy (0.10)", "", f"- Input: {r['input']}. Bonuses: "
            + ", ".join(f"{k.replace('_', ' ')} +{v}" for k, v in r["bonuses"].items()) + f"; cap {r['cap']}.", ""]
    out += pts(r["pv_kwp_points"], "PV kWp")

    s = c["smart_energy_management"]
    out += ["", "### 2.7 Smart energy management (0.05)", "", f"- {s['combine']}", f"- {s['rule']}", ""]
    out += table(["Controls present", "Controls level"], [[", ".join(x["requires"]) or "none", x["sub_score"]] for x in s["levels"]])
    out += ["", f"Lighting: {s['lighting_justification']}"]

    gen, self_m2, d_sub, d_pts, r_pts = pv_example()
    out += ["", "## 3. Overlaps and why they are kept", "",
            "| Overlap | Components | Kept because | How big |", "| --- | --- | --- | --- |",
            "| Solar PV | renewable energy + energy intensity | " + ei["overlap_with_renewables"].replace("|", "/")
            + f" | Example below: {d_pts:.2f} points via intensity vs {r_pts:.1f} via renewables |",
            "| Fabric and heating vs rating | insulation, heating, glazing + energy efficiency | " + ins["justification"]
            + " | Bounded by the weights: the five lever components share 0.55 |",
            "| Lighting vs rating | smart energy management + energy efficiency | SAP already counts lighting; the "
            "component rewards the lever. Learned share, decision D-26 | ≤ 0.05 × 0.47 × 100 = 2.4 points |",
            "",
            "### PV overlap, sized",
            "",
            f"Every `ScoreResult` carries `pv_overlap_points` in the energy-intensity component's inputs: the intensity sub-score with self-consumed PV added back "
            f"(default self-consumption share {PV_SELF_CONSUMPTION_DEFAULT:.0%}, LLD 4.1.1), times its weight. Worked example "
            f"(4 kWp, 850 kWh/kWp/yr, 95 m², metered 170 kWh/m²): generation {gen:,.0f} kWh/yr, self-consumed "
            f"{self_m2:.1f} kWh/m²; intensity sub-score changes by {d_sub:.1f} → **{d_pts:.2f} score points** of overlap, "
            f"against {r_pts:.1f} points from the renewables component. The score is shown with and without PV added back.",
            "",
            "## 4. Post-retrofit (projected) score",
            "",
            "The projected score re-scores the home after a package: the recorded features are edited by "
            "`greentwin/retrofit/property_edits.py`, intensity comes from the twin's package run (anchored to the meters), and "
            "energy efficiency uses the `sap_estimator.json` `RatingEstimate`, labelled \"estimated rating, not an EPC\". A "
            "package that only improves inputs never lowers the score (test `test_property_after_and_projected_score_not_lower`).",
            "",
            "## 5. Tests that guard this document",
            "",
            "- `tests/test_score.py`: monotonicity sweeps on every sub-score, every heating system mapped, weights sum to 1, "
            "half-up rounding, band of the rounded score, missing data widens never zeroes, projected ≥ current.",
            "- `tests/test_retrofit_engine.py`: projected score after a package is not lower.",
            ""]
    (ROOT / "docs" / "SCORE.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/SCORE.md")


if __name__ == "__main__":
    main()
